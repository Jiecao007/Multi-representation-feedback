"""Compact API wire format; expand deterministically into the existing editor schema.

Only syntax and unused research prose are reduced. Coordinates, individual paths,
visible text, grouping, provenance and ambiguity survive expansion unchanged.
"""
from typing import Literal, Optional
from pydantic import Field
from schema import Strict, validate_sketch


class CompactStroke(Strict):
    k: Literal['polyline', 'polygon', 'ellipse', 'rect', 'text']
    p: list[float]
    t: str
    f: bool
    c: Optional[str] = Field(pattern=r'^#[0-9a-fA-F]{6}$')


class CompactObject(Strict):
    id: str
    label: str
    text: str
    kind: str
    b: list[float] = Field(min_length=4, max_length=4)
    g: list[CompactStroke]
    m: list[str]
    o: Literal['student', 'template', 'uncertain']
    q: float = Field(ge=0, le=1)
    e: str
    a: str


class CompactRelation(Strict):
    id: str
    s: Optional[str]
    t: Optional[str]
    d: Literal['forward', 'backward', 'both', 'none', 'uncertain']
    p: list[float] = Field(min_length=4)
    text: str
    l: list[float] = Field(min_length=2, max_length=2)
    c: Optional[str] = Field(pattern=r'^#[0-9a-fA-F]{6}$')
    o: Literal['student', 'template', 'uncertain']
    q: float = Field(ge=0, le=1)
    e: str
    a: str


class CompactSketch(Strict):
    title: str
    summary: str
    objects: list[CompactObject]
    relations: list[CompactRelation]
    uncertainties: list[str]
    omitted_details: list[str]


def points(flat):
    if len(flat) % 2:
        raise ValueError('Coordinate arrays must contain complete x,y pairs')
    return [dict(x=flat[i], y=flat[i+1]) for i in range(0,len(flat),2)]


def expand(value):
    wire=CompactSketch.model_validate(value)
    objects=[]
    for o in wire.objects:
        objects.append(dict(id=o.id,label=o.label,verbatim_text=o.text,kind=o.kind,
            bbox=dict(zip(('x','y','width','height'),o.b)),
            glyph=[dict(kind=g.k,points=points(g.p),text=g.t,filled=g.f,color=g.c) for g in o.g],
            members=o.m,origin=o.o,confidence=o.q,evidence=o.e,ambiguity=o.a))
    relations=[dict(id=r.id,source=r.s,target=r.t,direction=r.d,points=points(r.p),
        verbatim_text=r.text,label_position=dict(zip(('x','y'),r.l)),color=r.c,
        origin=r.o,confidence=r.q,evidence=r.e,ambiguity=r.a,
        interpretation='Visible connector; causal or physical meaning is not independently established.') for r in wire.relations]
    # Conservative application defaults, not claims generated by the model.
    return validate_sketch(dict(title=wire.title,summary=wire.summary,
        representation='Visible student marks reconstructed as editable 2D objects.',
        objects=objects,relations=relations,uncertainties=wire.uncertainties,
        omitted_details=wire.omitted_details,
        simulation_readiness='qualitative_only' if relations else 'insufficient_structure',
        simulation_requirements=['Quantitative simulation readiness was not assessed in the compact reconstruction.'],
        suggested_interactions=['Move or resize a part','Edit text','Add or revise a connection']))


def pack(scene):
    """Lossless visual-field inverse, used for conversion regression fixtures only."""
    s=validate_sketch(scene)
    def flat(ps):return [v for p in ps for v in (p.x,p.y)]
    return CompactSketch.model_validate(dict(title=s.title,summary=s.summary,
        objects=[dict(id=o.id,label=o.label,text=o.verbatim_text,kind=o.kind,
            b=[o.bbox.x,o.bbox.y,o.bbox.width,o.bbox.height],
            g=[dict(k=g.kind,p=flat(g.points),t=g.text,f=g.filled,c=g.color) for g in o.glyph],
            m=o.members,o=o.origin,q=o.confidence,e=o.evidence,a=o.ambiguity) for o in s.objects],
        relations=[dict(id=r.id,s=r.source,t=r.target,d=r.direction,p=flat(r.points),text=r.verbatim_text,
            l=[r.label_position.x,r.label_position.y],c=r.color,o=r.origin,q=r.confidence,e=r.evidence,a=r.ambiguity) for r in s.relations],
        uncertainties=s.uncertainties,omitted_details=s.omitted_details))
